"""Compliance checks applied when a doctor reaches out to Digital MSL.

* sender gate   - only verified doctors may use any channel;
* rate limiting - a per-doctor ceiling on questions per minute;
* safety screen - patient-specific adverse events and product complaints must reach a
                  person (and pharmacovigilance) instead of getting an automated answer.
"""
from __future__ import annotations

import re
import threading
import time
from collections import defaultdict, deque
from typing import Optional

from digital_msl import doctor_registry
from digital_msl.config import get_dmsl_settings

NOT_VERIFIED_PREFIX = "Account not verified"

NOT_VERIFIED_MESSAGE = (
    f"{NOT_VERIFIED_PREFIX}: your registration is still being verified against the National Medical Register. "
    "You will be notified once it is confirmed. Contact your Physical MSL if this takes longer than expected."
)

RATE_LIMITED_MESSAGE = (
    "You are sending questions faster than Digital MSL can review them. "
    "Please wait a minute and try again."
)

ADVERSE_EVENT_ACK = (
    "Thank you for letting us know. What you described may be an adverse event or a product quality issue, "
    "so it has been sent directly to your Physical MSL team for follow-up and is not answered automatically. "
    "Please also report it through your organisation's official pharmacovigilance channel without delay, "
    "and include the product, batch number, patient details you are permitted to share, and the event outcome."
)

_lock = threading.Lock()
_hits: dict[str, deque[float]] = defaultdict(deque)


def check_rate_limit(user_id: str, *, now: Optional[float] = None) -> bool:
    """Record a request and return False when the doctor is over the per-minute limit.

    The window lives in this process; run a shared store (Redis) if the API is scaled out.
    """
    limit = get_dmsl_settings().rate_limit_per_minute
    if limit <= 0 or not user_id:
        return True
    current = time.monotonic() if now is None else now
    with _lock:
        window = _hits[user_id]
        while window and current - window[0] > 60:
            window.popleft()
        if len(window) >= limit:
            return False
        window.append(current)
    return True


def reset_rate_limits() -> None:
    with _lock:
        _hits.clear()


_ALWAYS_REPORT = re.compile(
    r"\b(product complaint|quality complaint|defective (?:vial|syringe|product|batch|pen)|contaminat\w+|"
    r"medication error|wrong dose|overdos\w+|counterfeit|fake (?:vial|product))\b",
    re.I,
)
_PATIENT_REF = re.compile(
    r"\b(my patient|our patient|a patient|the patient|one of my patients|patients? (?:of mine|in my clinic)|"
    r"he developed|she developed|they developed)\b",
    re.I,
)
_EVENT = re.compile(
    r"\b(developed|experienc\w+|suffered|presented with|reported|complain\w+ of|had a|"
    r"endophthalmitis|vasculitis|inflammation|uveitis|vision loss|lost vision|blindness|hospitali[sz]\w+|"
    r"died|death|anaphyla\w+|allergic reaction|reaction|seizure|stroke|infarction|hemorrhage|haemorrhage|"
    r"retinal detachment|adverse (?:event|reaction))\b",
    re.I,
)
_AFTER_TREATMENT = re.compile(r"\b(after|following|post|since|within \w+ (?:hours|days|weeks))\b", re.I)


def detect_adverse_event(text: str) -> Optional[str]:
    """Return a short reason when the message looks like an AE / complaint report, else None.

    Questions about adverse events in the literature ("what were the AEs in trial X?") are
    deliberately not flagged: a report needs a patient reference plus an event plus a timing cue,
    or an explicit product-complaint phrase.
    """
    body = str(text or "")
    if _ALWAYS_REPORT.search(body):
        return "product_complaint_or_medication_error"
    if _PATIENT_REF.search(body) and _EVENT.search(body) and _AFTER_TREATMENT.search(body):
        return "patient_adverse_event"
    return None


def sender_block_reason(user: Optional[dict]) -> Optional[str]:
    """Why this sender may not use Digital MSL, or None when allowed."""
    if user is None:
        if get_dmsl_settings().allow_unregistered_senders:
            return None
        return "unregistered"
    if user.get("role") == "doctor" and (user.get("status") or "active") != "active":
        return "disabled"
    if not doctor_registry.is_verified(user):
        return "not_verified"
    return None


